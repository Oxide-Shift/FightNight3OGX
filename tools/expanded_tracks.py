"""Canonical expanded rotation and full-track BS.1770 integrated loudness."""
from pathlib import Path
import json

ARTIST = "FN3OGX"
TRACKS = (
    ("Still Want the Crown", -15.31),
    ("Blood + Sweat", -15.45),
    ("Corner Talk", -15.35),
    ("Gate Money", -15.64),
    ("Heavy Hands", -15.76),
    ("Make It Two", -16.10),
    ("The Contender", -15.43),
    ("The Long Count", -15.83),
    ("Upstairs Neighbor", -15.58),
)
EXPANDED = tuple(title for title, _ in TRACKS)
JAVA = Path(__file__).resolve().parents[1] / "android/src/org/oxideshift/corner/ExpandedTracks.java"


def java_source():
    titles = ",\n        ".join(json.dumps(s) for s in EXPANDED)
    levels = ", ".join(f"{level:.2f}" for _, level in TRACKS)
    return f'''package org.oxideshift.corner;

/** Generated by tools/expanded_tracks.py. */
final class ExpandedTracks {{
    static final String ARTIST={json.dumps(ARTIST)};
    static final String[] TITLES={{
        {titles}}};
    static final double[] LUFS={{{levels}}};
    static int index(String stem){{
        for(int i=0;i<TITLES.length;i++)if(TITLES[i].equals(stem))return i;
        return -1;
    }}
}}
'''


def verify():
    if JAVA.read_text(encoding="utf-8") != java_source():
        raise ValueError("Expanded soundtrack changed. Regenerate ExpandedTracks.java with tools/expanded_tracks.py.")


if __name__ == "__main__":
    JAVA.write_text(java_source(), encoding="utf-8", newline="\n")
